    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
         if (jTextField1.getText().equals("") ||
        jTextArea1.getText().equals("") ||
        jTextArea2.getText().equals("") ||
        jTextField4.getText().equals("")) {

        JOptionPane.showMessageDialog(this, "Please fill all required fields");
        return;
    }

    try {
        Connection con = ConnectionProvider.getCon();
        String sql = "INSERT INTO prescription " +
                     "(patient_id, patient_name, diagnosis, medicines, dosage, doctor_name, prescription_date) " +
                     "VALUES (?, ?, ?, ?, ?, ?, ?)";

        PreparedStatement ps = con.prepareStatement(sql);
        ps.setInt(1, Integer.parseInt(jTextField1.getText()));
        ps.setString(2, jTextField2.getText());
        ps.setString(3, jTextArea1.getText());
        ps.setString(4, jTextArea2.getText());
        ps.setString(5, jTextField3.getText());
        ps.setString(6, jTextField4.getText());
        ps.setDate(7, new java.sql.Date(System.currentTimeMillis()));

        ps.executeUpdate();
        JOptionPane.showMessageDialog(this, "Prescription Saved Successfully");

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e);
    }
    }//GEN-LAST:event_jButton2ActionPerformed

