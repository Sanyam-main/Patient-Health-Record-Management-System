    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
       String id = jTextField1.getText();
String name = jTextField2.getText();
String number = jTextField3.getText();
String gender = jTextField4.getText();
String guardian = jTextField5.getText();
String guardiancontact = jTextField6.getText();
String aadhar = jTextField7.getText();
String age = jTextField8.getText();
String room = jTextField9.getText();
String ward = jTextField10.getText();
String doctor = jTextField11.getText();
String disease = jTextField12.getText();

try {
    Connection con = ConnectionProvider.getCon();

    PreparedStatement ps = con.prepareStatement(
        "UPDATE patienthealth SET "
        + "patient_name = ?, "
        + "patient_contact = ?, "
        + "gender = ?, "
        + "guardian_name = ?, "
        + "guardian_contact = ?, "
        + "aadhar = ?, "
        + "age = ?, "
        + "room_no = ?, "
        + "ward = ?, "
        + "assigned_doctor = ?, "
        + "diagnosed_disease = ? "
        + "WHERE id = ?"
    );

    ps.setString(1, name);
    ps.setString(2, number);
    ps.setString(3, gender);
    ps.setString(4, guardian);
    ps.setString(5, guardiancontact);
    ps.setString(6, aadhar);
    ps.setString(7, age);
    ps.setString(8, room);
    ps.setString(9, ward);
    ps.setString(10, doctor);
    ps.setString(11, disease);

    // WHERE id = ?
    ps.setString(12, id);

    ps.executeUpdate();

    JOptionPane.showMessageDialog(null, "Successfully Updated");

} catch (Exception e) {
    JOptionPane.showMessageDialog(null, e);
}

      
        
    }//GEN-LAST:event_jButton2ActionPerformed

